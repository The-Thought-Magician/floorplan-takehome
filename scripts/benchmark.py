"""Benchmark report: every processed capture against its ground truth, all tiers.

    uv run python scripts/benchmark.py [--out docs/benchmark.md]

Inputs: data/sample/*/summary.json and plan*.json, data/captures/*/plan*.json,
data/ground_truth/*.json (each names the captures it applies to). Writes a Markdown
report with per-tier wall, height and opening errors, the repeatability table for
rooms captured twice, drift ablation, timing, and gate pass/fail.
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GATES = {
    "lidar": {"wall_pct": 1.0, "height_cm": 1.5, "opening_cm": 2.0},
    "depth": {"wall_pct": 1.0, "height_cm": 1.5, "opening_cm": 2.0},
    "video": {"wall_pct": 3.0, "height_cm": 1.5, "opening_cm": 2.0},
    "photos": {"wall_pct": 8.0, "height_cm": 1.5, "opening_cm": 2.0},
}


def load_plans(capture_dir: Path) -> dict[str, dict]:
    plans = {}
    for f in capture_dir.glob("plan*.json"):
        tier = "depth" if f.stem == "plan" else f.stem.replace("plan_", "")
        if tier.endswith("drift_off"):
            continue
        try:
            plan = json.loads(f.read_text())
        except json.JSONDecodeError:
            continue
        if plan.get("capture", {}).get("format") == "stray_scanner" and tier == "depth":
            tier = "lidar"
        plans[tier] = plan
    return plans


def match_room(plan: dict, gt: dict) -> dict | None:
    """Ground truth names one room; pick the plan room whose area is closest to length x width."""
    rooms = [r for r in plan.get("rooms", []) if r.get("polygon_cm")]
    if not rooms:
        return None
    if "length_cm" in gt and "width_cm" in gt:
        target = gt["length_cm"] * gt["width_cm"] / 1e4
        return min(rooms, key=lambda r: abs((r.get("area_m2") or 0) - target))
    return rooms[0]


def wall_errors(room: dict, gt: dict) -> list[tuple[str, float, float, float]]:
    """(name, measured, truth, pct error) for the two GT dimensions against the two distinct wall lengths."""
    lengths = sorted(room.get("wall_lengths_cm") or [])
    if len(lengths) < 2 or "length_cm" not in gt:
        return []
    # a rectangle has two distinct lengths: the median of the smaller half and the larger half
    n = len(lengths)
    short, long_ = lengths[: n // 2], lengths[n // 2 :]
    short_v = sorted(short)[len(short) // 2]
    long_v = sorted(long_)[len(long_) // 2]
    out = []
    for name, meas, truth in (("length", long_v, gt["length_cm"]), ("width", short_v, gt["width_cm"])):
        out.append((name, meas, truth, (meas - truth) / truth * 100))
    return out


def main(out_path: Path) -> None:
    gts = {}
    for f in (ROOT / "data" / "ground_truth").glob("*.json"):
        gt = json.loads(f.read_text())
        for cid in gt.get("captures", []):
            gts[cid] = gt

    lines = ["# Benchmark report", "", "Generated by scripts/benchmark.py from plan outputs and data/ground_truth.", ""]
    rows, repeat, timing = [], {}, []
    for base in (ROOT / "data" / "captures", ROOT / "data" / "sample"):
        if not base.exists():
            continue
        for cdir in sorted(p for p in base.iterdir() if p.is_dir()):
            plans = load_plans(cdir)
            if not plans:
                continue
            gt = gts.get(cdir.name)
            summ = cdir / "summary.json"
            if summ.exists():
                t = json.loads(summ.read_text()).get("timing", {})
                timing.append((cdir.name, t))
            for tier, plan in sorted(plans.items()):
                room = match_room(plan, gt) if gt else (plan["rooms"][0] if plan.get("rooms") else None)
                n_rooms = len(plan.get("rooms", []))
                closed = bool(room and room.get("polygon_cm"))
                height = room.get("wall_height_cm") if room else None
                row = {"capture": cdir.name, "tier": tier, "rooms": n_rooms, "closed": closed, "height_cm": height, "walls": [], "height_err_cm": None, "gt": bool(gt)}
                if gt and room:
                    row["walls"] = wall_errors(room, gt)
                    if height is not None and gt.get("ceiling_height_cm"):
                        row["height_err_cm"] = height - gt["ceiling_height_cm"]
                    repeat.setdefault((gt["room"], tier), []).append((cdir.name, room.get("wall_lengths_cm"), height))
                rows.append(row)

    lines += ["## Per capture, per tier", "", "| capture | tier | rooms | closed | wall errors (measured / truth cm, pct) | height cm (err) | wall gate | height gate |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        gate = GATES.get(r["tier"], GATES["photos"])
        walls = "; ".join(f"{n}: {m:.0f}/{t:.0f} ({e:+.1f}%)" for n, m, t, e in r["walls"]) or ("no ground truth" if not r["gt"] else "no polygon")
        wall_gate = "n/a" if not r["walls"] else ("PASS" if all(abs(e) <= gate["wall_pct"] for *_, e in r["walls"]) else "FAIL")
        h = "none" if r["height_cm"] is None else f"{r['height_cm']:.1f}" + (f" ({r['height_err_cm']:+.1f})" if r["height_err_cm"] is not None else "")
        h_gate = "n/a" if r["height_err_cm"] is None else ("PASS" if abs(r["height_err_cm"]) <= gate["height_cm"] else "FAIL")
        lines.append(f"| {r['capture']} | {r['tier']} | {r['rooms']} | {r['closed']} | {walls} | {h} | {wall_gate} | {h_gate} |")

    lines += ["", "## Repeatability (same room, same tier, two or more captures)", ""]
    any_rep = False
    for (room, tier), caps in sorted(repeat.items()):
        if len(caps) < 2:
            continue
        any_rep = True
        lines.append(f"**{room}, {tier}**")
        lines.append("")
        lines.append("| capture | wall lengths cm | height cm |")
        lines.append("|---|---|---|")
        for cid, walls, h in caps:
            lines.append(f"| {cid} | {walls} | {h} |")
        hs = [h for _, _, h in caps if h is not None]
        if len(hs) >= 2:
            spread = max(hs) - min(hs)
            lines.append("")
            lines.append(f"Height spread {spread:.1f} cm, gate 1.0 cm: {'PASS' if spread <= 1.0 else 'FAIL'}")
        lines.append("")
    if not any_rep:
        lines.append("No room has two captures at the same tier yet.")
        lines.append("")

    lines += ["## Drift ablation (LiDAR scans)", "", "| capture | drift rate deg/min | max correction deg | wall thickness off / on cm | rooms off / on |", "|---|---|---|---|---|"]
    for base in (ROOT / "data" / "sample", ROOT / "data" / "captures"):
        for cdir in sorted(base.glob("*")) if base.exists() else []:
            plan = cdir / "plan.json"
            if not plan.exists():
                continue
            d = (json.loads(plan.read_text()).get("diagnostics") or {}).get("drift")
            if not d or not isinstance(d.get("estimate"), dict):
                continue
            ab = d["ablation"]
            lines.append(f"| {cdir.name} | {d['estimate']['rate_deg_per_min']} | {d['estimate']['max_correction_deg']} | {ab['off'].get('mean_wall_thickness_cm')} / {ab['on'].get('mean_wall_thickness_cm')} | {ab['off']['rooms']} / {ab['on']['rooms']} |")

    lines += ["", "## Timing (seconds)", "", "| capture | " + " | ".join(sorted({k for _, t in timing for k in t})) + " |"]
    keys = sorted({k for _, t in timing for k in t})
    lines.append("|---|" + "---|" * len(keys))
    for cid, t in timing:
        lines.append(f"| {cid} | " + " | ".join(str(t.get(k, "")) for k in keys) + " |")

    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path} with {len(rows)} rows")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "benchmark.md"))
    main(Path(ap.parse_args().out))
